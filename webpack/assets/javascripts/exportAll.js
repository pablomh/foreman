const fs = require('fs');
const path = require('path');

const pluginApi = require('../../../config/plugin_api');
const { exportKeyFor } = require('../../../config/plugin_import_key');

const apiEntryFor = relativePath =>
  pluginApi.find(entry => relativePath === entry);

const exportNameFor = relativeFilePath =>
  exportKeyFor(`/${relativeFilePath.replace(/\\/g, '/')}`);

const isExportableFile = fileName => {
  const { name, ext } = path.parse(fileName);
  return (
    ext === '.js' &&
    !fileName.endsWith('.test.js') &&
    !fileName.endsWith('.fixtures.js') &&
    !fileName.endsWith('mockRequests.js') &&
    !fileName.endsWith('vendor-core.scss') &&
    !fileName.endsWith('jquery.js') &&
    !name.includes('TestHelper') &&
    !name.includes('testHelper') &&
    !name.includes('APITestSetup')
  );
};

const modulePathFor = (directoryPath, fileName) => {
  let relativeFilePath = path.relative(
    __dirname,
    path.join(directoryPath, path.parse(fileName).name)
  );
  relativeFilePath = relativeFilePath.substring(
    relativeFilePath.indexOf('react_app') + 'react_app'.length + 1
  );
  return relativeFilePath.replace(/\\/g, '/');
};

const collectModules = (directoryPath, modules = []) => {
  fs.readdirSync(directoryPath, { withFileTypes: true }).forEach(dirent => {
    if (
      dirent.isDirectory() &&
      dirent.name !== '__mocks__' &&
      dirent.name !== '__tests__'
    ) {
      collectModules(path.join(directoryPath, dirent.name), modules);
    } else if (dirent.isFile() && isExportableFile(dirent.name)) {
      modules.push(modulePathFor(directoryPath, dirent.name));
    }
  });
  return modules;
};

const exportableModules = () =>
  collectModules(path.join(__dirname, 'react_app'))
    .map(relativePath => ({
      relativePath,
      apiEntry: apiEntryFor(relativePath),
    }))
    .filter(({ apiEntry }) => apiEntry);

const exportedKeys = () =>
  new Set(
    exportableModules().map(({ relativePath }) => exportNameFor(relativePath))
  );

const generateExportsFile = () => {
  const modules = exportableModules();

  const staleEntries = pluginApi.filter(
    entry => !modules.some(module => module.apiEntry === entry)
  );
  if (staleEntries.length) {
    throw new Error(
      `config/plugin_api.js lists paths that do not exist: ${staleEntries.join(
        ', '
      )}`
    );
  }

  const exportFileContent = modules
    .map(({ relativePath }) => {
      const fileName = exportNameFor(relativePath);
      return `import * as ${fileName} from './react_app/${relativePath}';\nexport { ${fileName} };\n`;
    })
    .join('');

  fs.writeFileSync(
    path.join(__dirname, 'all_react_app_exports.js'),
    `/* eslint-disable */\n// This file is autogenerated by the webpack/assets/javascripts/exportAll.js script\n// Please do not modify this file directly\n\n${exportFileContent}`
  );
};

module.exports = {
  generateExportsFile,
  exportNameFor,
  apiEntryFor,
  exportableModules,
  exportedKeys,
};
